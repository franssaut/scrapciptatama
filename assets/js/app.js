// Simulasi Kalkulator KPR
function setupKprCalculator() {
  const priceInput = document.getElementById('kprPrice');
  const dpPercentInput = document.getElementById('kprDpPercent');
  const tenorInput = document.getElementById('kprTenor');
  const rateInput = document.getElementById('kprRate');

  const dpNominalEl = document.getElementById('kprDpNominal');
  const loanNominalEl = document.getElementById('kprLoanNominal');
  const monthlyEl = document.getElementById('kprMonthlyInstallment');

  function calculateKpr() {
    if (!priceInput || !monthlyEl) return;
    const price = parseFloat(priceInput.value) || 0;
    const dpPercent = parseFloat(dpPercentInput.value) || 10;
    const tenorYears = parseFloat(tenorInput.value) || 15;
    const annualRate = parseFloat(rateInput.value) || 6.5;

    const dpNominal = price * (dpPercent / 100);
    const loanAmount = Math.max(0, price - dpNominal);

    // Rumus Anuitas Bulanan: P * (r / (1 - (1+r)^-n))
    const monthlyRate = (annualRate / 100) / 12;
    const totalMonths = tenorYears * 12;

    let monthlyInstallment = 0;
    if (monthlyRate > 0 && totalMonths > 0 && loanAmount > 0) {
      monthlyInstallment = loanAmount * (monthlyRate / (1 - Math.pow(1 + monthlyRate, -totalMonths)));
    }

    const fmt = (num) => "Rp " + Math.round(num).toLocaleString('id-ID');

    if (dpNominalEl) dpNominalEl.textContent = fmt(dpNominal);
    if (loanNominalEl) loanNominalEl.textContent = fmt(loanAmount);
    if (monthlyEl) monthlyEl.textContent = fmt(monthlyInstallment) + " /bln";
  }

  [priceInput, dpPercentInput, tenorInput, rateInput].forEach(el => {
    if (el) el.addEventListener('input', calculateKpr);
  });

  calculateKpr();
}

